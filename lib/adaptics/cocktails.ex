  @doc """
  Classifies a raw ingredient name as `{:spirit, id}` or
  `{:supporting, category}`. Unmatched names fall through to
  `{:supporting, :other}`.
  """
  def classify_ingredient(name) do
    downcased = String.downcase(name)

    Enum.find_value(@rules, {:supporting, :other}, fn {needle, result} ->
      if String.contains?(downcased, needle), do: result
    end)
  end

  @doc """
  Reads all drinks for a dataset from priv (or an explicit base dir, used by
  tests). Returns `[]` when the dataset directory has not been vendored yet,
  so /topo/cocktails degrades to an empty state instead of raising.
  """
  def list_drinks(dataset, base_dir \\ nil) do
    dir = if base_dir, do: Path.join(base_dir, dataset), else: data_dir(dataset)

    case File.ls(dir) do
      {:ok, files} ->
        files
        |> Enum.filter(&String.ends_with?(&1, ".json"))
        |> Enum.sort()
        |> Enum.map(fn file ->
          dir |> Path.join(file) |> File.read!() |> Jason.decode!()
        end)

      {:error, _} ->
        []
    end
  end

  @doc """
  The full structure serialized into the topo page's `data-cocktails`
  attribute: every dataset, self-contained, so the client can switch datasets
  without another request. Edges are not serialized — the client derives
  drink→spirit and drink→ingredient edges from each drink's id lists.
  """
  def payload(base_dir \\ nil) do
    %{datasets: Enum.map(@datasets, &dataset_payload(&1, base_dir))}
  end

  defp dataset_payload(%{id: id, label: label}, base_dir) do
    drinks =
      for drink <- list_drinks(id, base_dir) do
        {spirits, supporting} = split_ingredients(drink["ingredients"] || [])

        %{
          id: drink["slug"],
          name: drink["name"],
          category: drink["category"],
          spirits: if(spirits == [], do: [@unclassified], else: spirits),
          ingredients: supporting
        }
      end

    spirit_counts = count_references(drinks, & &1.spirits)

    supporting_index =
      for drink <- list_drinks(id, base_dir),
          ingredient <- drink["ingredients"] || [],
          {:supporting, category} <- [classify_ingredient(ingredient["name"])],
          into: %{} do
        {slugify(ingredient["name"]), %{name: ingredient["name"], category: category}}
      end

    ingredient_counts = count_references(drinks, & &1.ingredients)

    %{
      id: id,
      label: label,
      count: length(drinks),
      spirits:
        for {spirit, count} <- Enum.sort_by(spirit_counts, &(-elem(&1, 1))) do
          %{id: spirit, name: @spirit_labels[spirit] || spirit, count: count}
        end,
      ingredients:
        for {ing_id, count} <- Enum.sort_by(ingredient_counts, &(-elem(&1, 1))) do
          entry = supporting_index[ing_id]
          %{id: ing_id, name: entry.name, category: entry.category, count: count}
        end,
      drinks: drinks
    }
  end

  # Splits a drink's raw ingredients into {unique spirit ids, unique
  # supporting-ingredient ids}, preserving recipe order.
  defp split_ingredients(ingredients) do
    classified =
      for ingredient <- ingredients do
        {ingredient["name"], classify_ingredient(ingredient["name"])}
      end

    spirits = for {_name, {:spirit, id}} <- classified, do: id
    supporting = for {name, {:supporting, _}} <- classified, do: slugify(name)
    {Enum.uniq(spirits), Enum.uniq(supporting)}
  end

  defp count_references(drinks, get_ids) do
    drinks
    |> Enum.flat_map(get_ids)
    |> Enum.frequencies()
  end

  defp slugify(name) do
    name
    |> String.downcase()
    |> String.normalize(:nfd)
    |> String.replace(~r/[^a-z0-9]+/, "-")
    |> String.trim("-")
  end

  defp data_dir(dataset) do
    Application.app_dir(:adaptics, Path.join(["priv", "data", "cocktails", dataset]))
  end
end
